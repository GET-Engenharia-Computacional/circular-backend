import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { schemaStatements } from './schema';

const sql = `-- LocalizaUFJF: MySQL 8.0.22+ / InnoDB. Generated by npm run schema:export.
-- Run against a NEW database. No existing data is dropped.
CREATE DATABASE IF NOT EXISTS localizaufjf CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE localizaufjf;
SET time_zone = '+00:00';

${schemaStatements.join(';\n\n')};

-- Register the initial migration so later npm run migration:run does not recreate tables.
CREATE TABLE migrations (id INT NOT NULL AUTO_INCREMENT PRIMARY KEY, timestamp BIGINT NOT NULL, name VARCHAR(255) NOT NULL);
INSERT INTO migrations(timestamp,name) VALUES (1761600000000,'InitialSchema1761600000000');
`;
mkdirSync(resolve(process.cwd(), 'sql'), { recursive: true });
writeFileSync(resolve(process.cwd(), 'sql/schema.sql'), sql, 'utf8');
console.log('Generated sql/schema.sql');
